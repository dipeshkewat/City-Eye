// Computed stats helper
export function computeStats(reports) {
  const total = reports.length;
  const byStatus = {};
  const bySeverity = {};
  const byType = {};
  const byDepartment = {};

  reports.forEach((r) => {
    byStatus[r.status] = (byStatus[r.status] || 0) + 1;
    bySeverity[r.detection.severity_label] = (bySeverity[r.detection.severity_label] || 0) + 1;
    byType[r.detection.problem_type] = (byType[r.detection.problem_type] || 0) + 1;
    byDepartment[r.recommended_department] = (byDepartment[r.recommended_department] || 0) + 1;
  });

  return { total, byStatus, bySeverity, byType, byDepartment };
}

